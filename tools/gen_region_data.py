#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate compact province/city/district tables from QWeather's CSV."""
import csv
import json
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(__file__).with_name("China-City-List-latest.csv")
HEADER = ROOT / "main" / "region_data.h"
SOURCE_C = ROOT / "main" / "region_data.c"


def cstr(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    with SOURCE.open(encoding="utf-8-sig", newline="") as f:
        next(f)  # QWeather source/version row
        rows = list(csv.DictReader(f))

    tree = OrderedDict()
    for row in rows:
        if row["ISO_3166_1"] != "CN":
            continue
        province = row["Adm1_Name_ZH"].strip()
        city = row["Adm2_Name_ZH"].strip()
        district = row["Location_Name_ZH"].strip()
        location_id = row["Location_ID"].strip()
        if not (province and city and district and location_id):
            continue
        tree.setdefault(province, OrderedDict()).setdefault(city, []).append(
            (district, location_id)
        )

    names = []
    name_index = {}

    def intern(value):
        if value not in name_index:
            name_index[value] = len(names)
            names.append(value)
        return name_index[value]

    provinces, cities, districts = [], [], []
    for province_name, city_map in tree.items():
        first_city = len(cities)
        for city_name, district_rows in city_map.items():
            first_district = len(districts)
            seen = set()
            for district_name, location_id in district_rows:
                key = (district_name, location_id)
                if key in seen:
                    continue
                seen.add(key)
                districts.append((intern(district_name), intern(location_id)))
            cities.append((intern(city_name), first_district, len(districts) - first_district))
        provinces.append((intern(province_name), first_city, len(cities) - first_city))

    HEADER.write_text(
        """// Generated by tools/gen_region_data.py from QWeather LocationList.\n#pragma once\n#include <stdbool.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\nint region_province_count(void);\nconst char *region_province_name(int province);\nint region_city_count(int province);\nconst char *region_city_name(int province, int city);\nint region_district_count(int province, int city);\nconst char *region_district_name(int province, int city, int district);\nconst char *region_location_id(int province, int city, int district);\nbool region_find_location(const char *location_id, int *province, int *city, int *district);\n\n#ifdef __cplusplus\n}\n#endif\n""",
        encoding="utf-8",
    )

    out = [
        "// Generated by tools/gen_region_data.py from QWeather LocationList.",
        '#include "region_data.h"',
        "#include <string.h>",
        "#include <stdint.h>",
        "",
        "typedef struct { uint16_t name, first_city, city_count; } province_t;",
        "typedef struct { uint16_t name, first_district, district_count; } city_t;",
        "typedef struct { uint16_t name, location_id; } district_t;",
        "",
        f"static const char *const strings[{len(names)}] = {{",
    ]
    out.extend(f"    {cstr(value)}," for value in names)
    out.extend(["};", "", f"static const province_t provinces[{len(provinces)}] = {{"])
    out.extend(f"    {{{n}, {first}, {count}}}," for n, first, count in provinces)
    out.extend(["};", "", f"static const city_t cities[{len(cities)}] = {{"])
    out.extend(f"    {{{n}, {first}, {count}}}," for n, first, count in cities)
    out.extend(["};", "", f"static const district_t districts[{len(districts)}] = {{"])
    out.extend(f"    {{{n}, {location_id}}}," for n, location_id in districts)
    out.extend(
        [
            "};",
            "",
            "int region_province_count(void) { return (int)(sizeof(provinces) / sizeof(provinces[0])); }",
            "const char *region_province_name(int p) {",
            "    return (p >= 0 && p < region_province_count()) ? strings[provinces[p].name] : \"\";",
            "}",
            "int region_city_count(int p) {",
            "    return (p >= 0 && p < region_province_count()) ? provinces[p].city_count : 0;",
            "}",
            "const char *region_city_name(int p, int c) {",
            "    if (p < 0 || p >= region_province_count() || c < 0 || c >= provinces[p].city_count) return \"\";",
            "    return strings[cities[provinces[p].first_city + c].name];",
            "}",
            "int region_district_count(int p, int c) {",
            "    if (p < 0 || p >= region_province_count() || c < 0 || c >= provinces[p].city_count) return 0;",
            "    return cities[provinces[p].first_city + c].district_count;",
            "}",
            "static const district_t *district_at(int p, int c, int d) {",
            "    if (p < 0 || p >= region_province_count() || c < 0 || c >= provinces[p].city_count) return 0;",
            "    const city_t *city = &cities[provinces[p].first_city + c];",
            "    if (d < 0 || d >= city->district_count) return 0;",
            "    return &districts[city->first_district + d];",
            "}",
            "const char *region_district_name(int p, int c, int d) {",
            "    const district_t *item = district_at(p, c, d);",
            "    return item ? strings[item->name] : \"\";",
            "}",
            "const char *region_location_id(int p, int c, int d) {",
            "    const district_t *item = district_at(p, c, d);",
            "    return item ? strings[item->location_id] : \"\";",
            "}",
            "bool region_find_location(const char *id, int *out_p, int *out_c, int *out_d) {",
            "    if (!id || !*id) return false;",
            "    for (int p = 0; p < region_province_count(); p++) {",
            "        for (int c = 0; c < provinces[p].city_count; c++) {",
            "            const city_t *city = &cities[provinces[p].first_city + c];",
            "            for (int d = 0; d < city->district_count; d++) {",
            "                const district_t *item = &districts[city->first_district + d];",
            "                if (strcmp(strings[item->location_id], id) == 0) {",
            "                    if (out_p) *out_p = p;",
            "                    if (out_c) *out_c = c;",
            "                    if (out_d) *out_d = d;",
            "                    return true;",
            "                }",
            "            }",
            "        }",
            "    }",
            "    return false;",
            "}",
            "",
        ]
    )
    SOURCE_C.write_text("\n".join(out), encoding="utf-8")
    print(f"Generated {len(provinces)} provinces, {len(cities)} cities, {len(districts)} regions, {len(names)} strings")


if __name__ == "__main__":
    main()
